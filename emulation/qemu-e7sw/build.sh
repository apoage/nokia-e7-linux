#!/bin/bash
# build.sh — compile the SWBL-role guest blobs with the musl.cc ARMv6
# cross (task 103) and emit the embedded-array header QEMU loads them
# from.  Output:
#   shim.bin  — boot shim (loaded at 0x40200000, SRAM bottom)
#   ../qemu/hw/arm/e7sw_blobs.h — regenerated header (committed)
#
# The task-104 lld.bin (vtable trampolines + LLD body) is RETIRED (task
# 118): NLoader's genuine FSR LLD rides the flash image at file
# 0xB000-0x10000 and the board maps it at its linked base 0x1001B000 —
# see docs/bcm2727-onenand.md §1.1.
set -e
cd "$(dirname "$0")"

CROSS="${CROSS:-../../toolchain/musl.cc/armv6-linux-musleabi-cross/bin/armv6-linux-musleabi-}"
CC="${CROSS}gcc"
OBJCOPY="${CROSS}objcopy"

CFLAGS="-mthumb -march=armv6 -mtune=arm1176jzf-s -Os -ffreestanding \
 -fno-builtin -fno-stack-protector -fno-common -nostdlib -nostartfiles \
 -static -no-pie -ffunction-sections -Wl,--build-id=none"

$CC $CFLAGS -I. -Wl,-T shim.ld -o shim.elf shim.c onenand_ll.c

$OBJCOPY -O binary shim.elf  shim.bin

python3 - <<'EOF'
import struct

def carray(name, path, base):
    data = open(path, 'rb').read()
    out = [f"/* generated by emulation/qemu-e7sw/build.sh — do not edit */",
           f"static const uint8_t {name}_bin[] = {{"]
    for i in range(0, len(data), 12):
        out.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i+12]) + ",")
    out += [f"}};",
            f"#define {name.upper()}_LOAD 0x{base:08x}u",
            f"#define {name.upper()}_SIZE  {len(data)}u",
            ""]
    return "\n".join(out), len(data), base

hdr = ["/*", " * e7sw_blobs.h — SWBL-role guest blobs (task 104),",
       " * generated by emulation/qemu-e7sw/build.sh. Do not edit.", " */",
       "#ifndef E7SW_BLOBS_H", "#define E7SW_BLOBS_H", "",
       "#include <stdint.h>", ""]
shim, ssz, sbase = carray("e7sw_shim", "shim.bin", 0x40200000)
hdr += [shim, "#endif /* E7SW_BLOBS_H */", ""]
open("../qemu/hw/arm/e7sw_blobs.h", "w").write("\n".join(hdr))
print(f"shim.bin {ssz} bytes @ 0x{sbase:08x}")
EOF
